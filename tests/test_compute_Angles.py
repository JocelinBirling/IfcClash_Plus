class TestComputeAngleBetween(unittest.TestCase):
    """The compute contract of AngleBetween: entities + named
    parameters."""

    @classmethod
    def setUpClass(cls):
        # ifcopenshell 0.9: an entity does not keep its file alive.
        cls.file = ifcopenshell.open(
            os.path.join(MODEL_DIR, "CuboidA_Orient_FallenCuboidA_90.ifc")
        )

    def _elements(self, *names):
        found = []
        for name in names:
            matches = [e for e in self.file.by_type("IfcProduct") if e.Name == name]
            assert matches, f"no element named {name!r}"
            found.append(matches[0])
        return found

    def _compute(self, source, target, **params):
        rule = AngleBetween(None, None, params["direction_method_for_source"],
                            params["direction_method_for_target"],
                            params["angle_difference"], params["angle_tolerance"])
        return rule.compute(self._elements(source), self._elements(target), **params)

    def test_ninety_degrees_detected(self):
        # [calibrated] the Wide directions of the two cuboids cross
        # at 90 deg.
        results = self._compute(
            "CuboidA", "FallenCuboidA",
            direction_method_for_source="Wide", direction_method_for_target="Wide",
            angle_difference=90, angle_tolerance=5,
        )
        self.assertEqual(len(results), 1)
        result = results[0]
        self.assertIsInstance(result, ClashResultTwoObjects)
        self.assertTrue(result.status)
        self.assertEqual(result.source.Name, "CuboidA")
        self.assertEqual(result.target.Name, "FallenCuboidA")

        # The measured angle and the two main directions of the pair.
        self.assertAlmostEqual(result.info.angle, 90.0, delta=1.0)
        labels = [axis.label for axis in result.info.axes]
        self.assertEqual(labels, ["source", "target"])

        self.assertEqual(result.info.validate(), [])
        assert_result_shape(SimpleNamespace(result=results))

    def test_wrong_expected_angle_not_detected(self):
        # The same pair measured against a 0 deg expectation: the
        # circular difference (90) leaves the 5 deg tolerance.
        results = self._compute(
            "CuboidA", "FallenCuboidA",
            direction_method_for_source="Wide", direction_method_for_target="Wide",
            angle_difference=0, angle_tolerance=5,
        )
        self.assertEqual(results, [])

    def test_compute_is_pure_of_management_and_display(self):
        rule = AngleBetween(None, None, "Wide", "Wide", 90, 5)
        rule.result.append("sentinel")
        rule.display_items.append("sentinel")

        results = self.compute_of(rule)

        self.assertEqual(len(results), 1)
        self.assertEqual(rule.result, ["sentinel"])
        self.assertEqual(rule.display_items, ["sentinel"])
        self.assertIsNone(rule.output)

    def compute_of(self, rule):
        sources = self._elements("CuboidA")
        targets = self._elements("FallenCuboidA")
        return rule.compute(sources, targets, "Wide", "Wide", 90, 5)


class TestComputeClearanceAxisToAxis(unittest.TestCase):
    """The compute contract of ClearanceAxisToAxis on generated
    models (two trays 0.5 m apart)."""

    @classmethod
    def setUpClass(cls):
        import tempfile

        temp_dir = tempfile.mkdtemp()
        cls._temp_dir = temp_dir
        cls.parallel_model = os.path.join(temp_dir, "parallel.ifc")
        make_model(
            cls.parallel_model,
            [
                box("TrayA", 0.0, dx=4.0, dy=0.1, height=0.1),
                box("TrayB", 0.0, y=0.5, dx=4.0, dy=0.1, height=0.1),
            ],
        )
        cls.file = ifcopenshell.open(cls.parallel_model)

    @classmethod
    def tearDownClass(cls):
        import shutil

        shutil.rmtree(cls._temp_dir, True)

    def _elements(self, *names):
        found = []
        for name in names:
            matches = [e for e in self.file.by_type("IfcProduct") if e.Name == name]
            assert matches, f"no element named {name!r}"
            found.append(matches[0])
        return found

    def _compute(self, source, target, **params):
        rule = ClearanceAxisToAxis(None, None, **params)
        return rule.compute(self._elements(source), self._elements(target), **params)

    def test_offset_in_interval_no_clash(self):
        # Two trays 0.5 m apart, valid between 0.4 and 0.6.
        results = self._compute(
            "TrayA", "TrayB", mode="Perpendicular",
            min_distance=0.4, max_distance=0.6,
        )
        self.assertEqual(results, [])

    def test_offset_too_far_clashes(self):
        # The same pair with a required minimum of 0.7 m: the 0.5 m
        # offset is too close -> a "too far" clash of min_distance.
        results = self._compute(
            "TrayA", "TrayB", mode="Perpendicular",
            min_distance=0.7,
        )
        self.assertEqual(len(results), 1)

    def test_info_blocks_of_a_verdict(self):
        """The verdict carries the measured axis-to-axis distance, the
        closest point pair, the mode with its degraded flag and the
        two support segments (axes block)."""
        results = self._compute(
            "TrayA", "TrayB", mode="Perpendicular",
            min_distance=0.7,
        )
        info = results[0].info

        self.assertAlmostEqual(info.distance, 0.5, delta=0.01)
        self.assertAlmostEqual(info.angle, 0.0, delta=0.5)
        self.assertEqual(info.axis_mode, "Perpendicular")
        self.assertFalse(info.axis_degraded)
        self.assertEqual(len(info.source_points), 1)
        self.assertEqual(len(info.target_points), 1)

        # The two support segments of the pair.
        labels = [axis.label for axis in info.axes]
        self.assertEqual(labels, ["source", "target"])
        for axis in info.axes:
            self.assertAlmostEqual(axis.length, 4.0, delta=0.1)
            self.assertAlmostEqual(abs(axis.direction[1]), 0.0, delta=0.01)

        self.assertEqual(info.validate(), [])
        assert_result_shape(SimpleNamespace(result=results))


class TestComputeAnglesDispatch(unittest.TestCase):
    """The flat JSON declarations drive the computes through the
    registry dispatch."""

    def test_engine_params(self):
        self.assertEqual(
            engine_params("AngleBetween"),
            [
                "direction_method_for_source",
                "direction_method_for_target",
                "angle_difference",
                "angle_tolerance",
            ],
        )
        self.assertEqual(
            engine_params("ClearanceAxisToAxis"),
            [
                "mode",
                "min_distance",
                "max_distance",
                "tolerance",
                "linearity_ratio",
                "on_non_linear",
                "parallel_tolerance",
            ],
        )

    def test_declaration_drives_anglebetween(self):
        from ifctester import ids
        from RuleClass import SelectFacet

        def select(name):
            s = SelectFacet()
            s.applicability = [ids.Attribute(name="Name", value=name)]
            return s

        rule = AngleBetween(select("CuboidA"), select("FallenCuboidA"),
                            "Wide", "Wide", 90, 5)
        config = json.loads(json.dumps(serialize_rule_check(rule)))

        file = ifcopenshell.open(
            os.path.join(MODEL_DIR, "CuboidA_Orient_FallenCuboidA_90.ifc")
        )
        sources = [[e for e in file.by_type("IfcProduct") if e.Name == "CuboidA"][0]]
        targets = [[e for e in file.by_type("IfcProduct") if e.Name == "FallenCuboidA"][0]]
        results = compute_from_config(config, sources, targets)
        self.assertEqual(len(results), 1)
        self.assertAlmostEqual(results[0].info.angle, 90.0, delta=1.0)


if __name__ == "__main__":
    unittest.main()
